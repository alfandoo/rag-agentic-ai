from datetime import datetime
from typing import List, Optional, Literal, Dict, Any
from pydantic import BaseModel, Field


class CompetitorFocus(BaseModel):
    """Represents an identified competitor to analyze."""
    name: str = Field(description="Name of the competitor or product")
    website: Optional[str] = Field(default=None, description="Official website or product URL")
    category: str = Field(description="Market category or niche (e.g., AI Code Editor, Payment Gateway)")
    core_value_prop: str = Field(description="Primary value proposition or tagline")


class ResearchSubtask(BaseModel):
    """A specific research angle generated by the Planner."""
    subtask_id: str = Field(description="Unique identifier e.g. task_1")
    focus_dimension: Literal["product_features", "pricing_model", "user_sentiment", "go_to_market"] = Field(
        description="The dimension of competitor analysis being investigated"
    )
    competitor_target: str = Field(description="Which competitor this task focuses on, or 'industry-wide'")
    search_queries: List[str] = Field(description="2-3 targeted search queries to fetch high-signal data")
    expected_findings: str = Field(description="What specific facts we need to confirm (e.g., pricing tiers, recent complaints)")


class ResearchPlan(BaseModel):
    """Structured research plan generated by the Market Planner Agent."""
    market_domain: str = Field(description="The overarching market or product category being evaluated")
    competitors: List[CompetitorFocus] = Field(description="List of primary competitors to analyze")
    subtasks: List[ResearchSubtask] = Field(description="Actionable subtasks broken down by dimension")
    key_hypotheses: List[str] = Field(description="Initial hypotheses to validate during research")


class SourceCitation(BaseModel):
    """Verified source citation with provenance tracking."""
    url: str = Field(description="Full URL of the source")
    title: str = Field(description="Page title or document headline")
    snippet: str = Field(description="Crucial quote or extracted factual excerpt")
    source_engine: Literal["google_grounding", "tavily", "duckduckgo"] = Field(
        description="Search engine tool that retrieved this source"
    )
    competitor: Optional[str] = Field(
        default=None,
        description="Specific competitor this source belongs to (e.g., Supabase, Firebase, Neon)"
    )
    dimension: Optional[str] = Field(
        default=None,
        description="Research subtask dimension this source supports (product_features, pricing_model, user_sentiment, go_to_market)"
    )
    retrieved_at: str = Field(default_factory=lambda: datetime.utcnow().isoformat())


class ExtractedEvidence(BaseModel):
    """Factual evidence gathered by the Intelligence Researcher."""
    competitor: str = Field(description="Competitor name")
    dimension: Literal["product_features", "pricing_model", "user_sentiment", "go_to_market"] = Field(
        description="The dimension this evidence relates to"
    )
    facts: List[str] = Field(description="Bullet points of verified facts, statistics, or quotes")
    citations: List[SourceCitation] = Field(default_factory=list, description="Associated source citations")


class VerificationVerdict(BaseModel):
    """Quality and fact-check verdict generated by the Auditor Node."""
    is_valid: bool = Field(description="True if evidence is sufficient, current, and verified")
    confidence_score: float = Field(
        ge=0.0, le=100.0,
        description="Confidence score (0-100) on data completeness, currency, and accuracy"
    )
    critique: str = Field(description="Detailed evaluation critique of the findings")
    missing_aspects: List[str] = Field(default_factory=list, description="Specific missing data points (if any)")
    retry_search_queries: List[str] = Field(
        default_factory=list,
        description="Precise search queries to run if confidence < 80% and retry is triggered"
    )


class SWOTAnalysis(BaseModel):
    """Standard 4-quadrant SWOT analysis for a competitor."""
    competitor: str = Field(description="Competitor name")
    strengths: List[str] = Field(description="Key strengths and advantages")
    weaknesses: List[str] = Field(description="Noted weaknesses and limitations")
    opportunities: List[str] = Field(description="Market opportunities and emerging growth areas")
    threats: List[str] = Field(description="External threats, competitive pressures, or risks")


class CompetitorProfile(BaseModel):
    """Deep-dive profile of an individual competitor."""
    name: str = Field(description="Competitor name")
    website: Optional[str] = Field(default=None, description="Official website URL")
    tagline: str = Field(description="Short description / value proposition")
    pricing_summary: str = Field(description="Pricing breakdown (tiers, free tier, enterprise pricing)")
    user_sentiment: Optional[str] = Field(
        default=None,
        description="Summary of real user sentiment, community reputation, developer/customer satisfaction, and common feedback"
    )
    key_features: List[str] = Field(description="Standout features and capabilities")
    pros: List[str] = Field(description="What users and analysts praise")
    cons: List[str] = Field(description="Common complaints or limitations")
    market_positioning: str = Field(description="Target audience and go-to-market positioning (e.g., solo developers, enterprise, mid-market)")


class CompetitorReport(BaseModel):
    """The final executive-level intelligence report synthesized by the Writer Agent."""
    title: str = Field(description="Title of the market intelligence report")
    executive_summary: str = Field(description="High-level executive briefing summarizing the competitive landscape")
    market_overview: str = Field(description="State of the market, growth trajectory, and key drivers")
    competitor_profiles: List[CompetitorProfile] = Field(description="Detailed profiles of each analyzed competitor")
    feature_matrix_markdown: str = Field(description="Markdown comparison table comparing all competitors side-by-side")
    pricing_matrix_markdown: str = Field(description="Markdown table summarizing pricing tiers and models")
    swot_analyses: List[SWOTAnalysis] = Field(description="SWOT breakdowns for each competitor")
    strategic_recommendations: List[str] = Field(description="Actionable strategic recommendations for market entry/competition")
    verified_citations: List[SourceCitation] = Field(description="Curated list of verified sources used in the report")
    confidence_score: Optional[float] = Field(default=None, description="Audited confidence score from Fact-Checker")
    audit_status: Optional[Literal["verified", "partial_evidence"]] = Field(default="verified", description="Audit status based on confidence threshold")
    audit_critique: Optional[str] = Field(default=None, description="Specific auditor explanation of the confidence score and evidence quality")
    missing_data_points: List[str] = Field(default_factory=list, description="Specific missing or unverified data points per competitor")
    generated_at: str = Field(default_factory=lambda: datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC"))
